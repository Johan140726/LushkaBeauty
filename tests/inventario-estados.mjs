/** Ejecutar: node tests/inventario-estados.mjs (npm install debe haberse ejecutado) */
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { strict as assert } from 'node:assert';
import vm from 'node:vm';
const require = createRequire(import.meta.url);
const ts = require('typescript');
const source = readFileSync(new URL('../src/app/services/inventario.ts', import.meta.url), 'utf8');
const converted = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const module = {exports:{}};
vm.runInNewContext(converted,{module,exports:module.exports,Set,Error}, {timeout:1000});
const { movimientoPorCambio: cambio, transicionesDisponibles: opciones, permiteRegularizar: regularizar } = module.exports;
assert.equal(cambio('Pendiente','Confirmado',false),'descontar');
assert.equal(cambio('Pendiente','Cancelado',false),'ninguno');
assert.equal(cambio('Confirmado','Cancelado',true),'devolver');
assert.equal(cambio('Confirmado','Cancelado',false),'ninguno');
assert.equal(cambio('Confirmado','En preparación',true),'ninguno');
assert.equal(cambio('En preparación','En camino',true),'ninguno');
assert.equal(cambio('En camino','Entregado',true),'ninguno');
assert.deepEqual([...opciones('Pendiente')],['Pendiente','Confirmado','Cancelado']);
assert.deepEqual([...opciones('Entregado')],['Entregado']);
assert.equal(regularizar('Confirmado',false,false),true);
assert.equal(regularizar('En preparación',false,false),true);
assert.equal(regularizar('Confirmado',true,false),false);
assert.equal(regularizar('Cancelado',false,false),false);
assert.throws(()=>cambio('Cancelado','Confirmado',false));
assert.throws(()=>cambio('Entregado','Cancelado',true));
assert.throws(()=>cambio('Confirmado','Confirmado',true));
assert.throws(()=>cambio('Pendiente','Entregado',false));
console.log('Inventario: 16 validaciones de transiciones y regularización superadas.');
